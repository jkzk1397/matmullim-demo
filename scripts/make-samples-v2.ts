type El = { name: string; levels: [string, number][] };
type Rubric = {
  name: string;
  max: number;
  task: string;
  codes: string[];
  method: string;
  els: El[];
  base: [number, number, number];
  /** 성취기준별 성취수준(A~E)을 표 안에 넣을지 */
  levels?: Record<string, string[]>;
};

const METHOD = (on: string[]) =>
  ['서술·논술', '구술·발표', '토의·토론', '프로젝트', '실험·실습', '포트폴리오', '기타'].map((m) => `${on.includes(m) ? '■' : '□'} ${m}`).join('  ') +
  '\n' +
  ['교사 관찰 평가 및 기록', '자기평가', '동료평가'].map((m) => `${on.includes(m) ? '■' : '□'} ${m}`).join('  ');

function rubricTable(title: string, r: Rubric): ParsedTable {
  const rows: C[][] = [
    ['평가 영역명', { t: r.name, cs: 2 }, '영역 만점', { t: `${r.max}점`, cs: 2 }],
    ['수행 과제', { t: r.task, cs: 5 }],
  ];
  if (r.levels) {
    rows.push(['교육과정 성취기준', { t: '성취기준별 성취수준', cs: 5 }]);
    for (const code of r.codes) {
      const lv = r.levels[code];
      if (!lv) throw new Error(`${code} 성취수준이 없어요`);
      'ABCDE'.split('').forEach((g, i) => rows.push([...(i === 0 ? [{ t: S(code), rs: 5 }] : []), g, { t: lv[i], cs: 4 }]));
    }
  } else rows.push(['교육과정 성취기준', { t: r.codes.map((c) => S(c)).join('\n'), cs: 5 }]);
  rows.push(['평가 방법', { t: r.method, cs: 5 }]);
  rows.push(['평가 요소', { t: '수행 수준(채점 기준)', cs: 4 }, '배점']);
  for (const e of r.els)
    e.levels.forEach(([crit, pts], i) => rows.push([...(i === 0 ? [{ t: e.name, rs: e.levels.length }] : []), { t: crit, cs: 4 }, String(pts)]));
  rows.push(['기본점수', { t: '', cs: 4 }, String(r.base[0])]);
  rows.push(['자발적 미참여자, 백지 제출자', { t: '', cs: 4 }, String(r.base[1])]);
  rows.push(['장기 미인정 결석자', { t: '', cs: 4 }, String(r.base[2])]);
  const total = r.els.reduce((s, e) => s + Math.max(...e.levels.map((l) => l[1])), 0);
  if (total !== r.max) throw new Error(`${r.name}: 배점 합 ${total} ≠ 영역 만점 ${r.max}`);
  return table(title, 6, rows);
}

