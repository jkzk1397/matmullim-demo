// ---------- 표 만들기 (HTML 표처럼 칸을 차례로 놓고 병합한 칸은 건너뛴다) ----------

type C = string | { t: string; cs?: number; rs?: number };

function table(title: string, width: number, rows: C[][]): ParsedTable {
  const taken = new Set<string>();
  const spans: Span[] = [];
  const grid: string[][] = [];
  const ensure = (r: number) => {
    while (grid.length <= r) grid.push(Array.from({ length: width }, () => ''));
  };
  rows.forEach((cells, r) => {
    ensure(r);
    let c = 0;
    for (const cell of cells) {
      while (taken.has(`${r},${c}`)) c++;
      const { t, cs = 1, rs = 1 } = typeof cell === 'string' ? { t: cell } : cell;
      if (c + cs > width) throw new Error(`표 "${title}" ${r}행: 칸이 너비 ${width}를 넘어요 (${t.slice(0, 20)})`);
      ensure(r + rs - 1);
      grid[r][c] = t;
      for (let i = r; i < r + rs; i++) for (let j = c; j < c + cs; j++) taken.add(`${i},${j}`);
      if (cs > 1 || rs > 1) spans.push({ row: r, col: c, rowSpan: rs, colSpan: cs });
      c += cs;
    }
  });
  return { title, rows: grid, spans };
}

/** "[코드] 고시 원문" */
function S(code: string, cur: Curriculum = '2022'): string {
  const e = lookupStandard(code, cur);
  if (!e) throw new Error(`${cur} DB에 ${code}가 없어요`);
  return `${code} ${e.text}`;
}
const text = (code: string, cur: Curriculum = '2022') => S(code, cur).slice(code.length + 1);

const pct = (n: number) => `${n}%`;
const score = (max: number, w: number) => `${max}점\n(${w}%)`;
