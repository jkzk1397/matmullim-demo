// ---------- 교수·학습 운영 계획 ----------

type SchedRow = { month: number; week: string; unit: string; std: string[]; method: string; evalm: string; focus: string };

/** std 항목이 코드뿐이면 2022 원문을 붙이고, 이미 문장이 있으면(심은 오류) 그대로 쓴다 */
const stdLine = (s: string) => (/\]\s*\S/.test(s) ? s : S(s));

function scheduleTable(title: string, rows: SchedRow[]): ParsedTable {
  const out: C[][] = [['월', '주', '단원명\n(영역명)', '교육과정 성취기준', '수업 방법', '평가 방법', '수업·평가 연계의 주안점']];
  for (let i = 0; i < rows.length; i++) {
    const r = rows[i];
    const cells: C[] = [];
    if (i === 0 || rows[i - 1].month !== r.month) {
      let n = 1;
      while (rows[i + n]?.month === r.month) n++;
      cells.push({ t: String(r.month), rs: n });
    }
    cells.push(r.week);
    if (i === 0 || rows[i - 1].unit !== r.unit) {
      let n = 1;
      while (rows[i + n]?.unit === r.unit) n++;
      cells.push(n > 1 ? { t: r.unit, rs: n } : r.unit);
    }
    cells.push(r.std.map(stdLine).join('\n'), r.method, r.evalm, r.focus);
    out.push(cells);
  }
  return table(title, 7, out);
}

// ---------- 평가의 종류와 반영비율 (요약표) ----------

type Area = { name: string; max: number; w: number; ratio?: string; essay?: number; codes: string[]; els: string[]; when: string };
type Exam = { sel: [number, number]; ess: [number, number]; codes: string[]; els: string[]; when: string };

function summaryTable(title: string, areas: Area[], opts: { exam?: Exam; essayTotal?: number; perfWeight?: number } = {}): ParsedTable {
  const n = areas.length;
  const ex = opts.exam;
  const essayVals = areas.map((a) => a.essay);
  const essayTotal = opts.essayTotal ?? (ex ? ex.ess[1] : 0) + essayVals.reduce<number>((s, v) => s + (v ?? 0), 0);
  const perfW = opts.perfWeight ?? areas.reduce((s, a) => s + a.w, 0);
  const cell = (a: Area) => a.ratio ?? score(a.max, a.w);
  const essayCell = (v?: number) => (v ? pct(v) : '-');
  if (!ex) {
    return table(title, n + 2, [
      ['평가 종류', { t: '수행평가', cs: n }, '합계'],
      ['반영 비율', { t: '100%', cs: n }, '100%'],
      ['영역', ...areas.map((a) => a.name), ''],
      ['영역 만점\n(반영비율)', ...areas.map(cell), '100%'],
      ['논술형 평가\n반영비율', ...essayVals.map(essayCell), pct(essayTotal)],
      ['교육과정\n성취기준', ...areas.map((a) => a.codes.join('\n')), ''],
      ['평가 요소', ...areas.map((a) => bullets(a.els)), ''],
      ['평가 시기', ...areas.map((a) => a.when), ''],
    ]);
  }
  const examW = ex.sel[1] + ex.ess[1];
  return table(title, n + 4, [
    ['평가 종류', { t: '정기시험', cs: 2 }, { t: '수행평가', cs: n }, '합계'],
    ['반영 비율', { t: pct(examW), cs: 2 }, { t: pct(perfW), cs: n }, '100%'],
    [{ t: '횟수/영역', rs: 2 }, { t: '2차', cs: 2 }, ...areas.map((a) => ({ t: a.name, rs: 2 })), ''],
    ['선택형', '논술형', ''],
    ['영역 만점\n(반영비율)', score(ex.sel[0], ex.sel[1]), score(ex.ess[0], ex.ess[1]), ...areas.map(cell), '100%'],
    ['논술형 평가\n반영비율', { t: pct(ex.ess[1]), cs: 2 }, ...essayVals.map(essayCell), pct(essayTotal)],
    ['교육과정\n성취기준', { t: ex.codes.join('\n'), cs: 2 }, ...areas.map((a) => a.codes.join('\n')), ''],
    ['평가 요소', { t: bullets(ex.els), cs: 2 }, ...areas.map((a) => bullets(a.els)), ''],
    ['평가 시기', { t: ex.when, cs: 2 }, ...areas.map((a) => a.when), ''],
  ]);
}

